<?php
/**
 * Etel-ID Premium — QR Code & Barcode Helper
 *
 * @package    Etel-ID Premium
 * @version    2.1.0
 * @author     Etel Group · ኢትኤል ቡድን
 * @link       https://etelgroup.com
 * @since      2.0.0
 *
 * Generates QR code <img> tags via api.qrserver.com and
 * Code128 barcode <img> tags via barcode.tec-it.com.
 *
 * CACHED LOCALLY as of 2.1.0 - these used to hotlink the external
 * service's URL directly into every single page view, meaning every
 * member's QR/barcode depended on api.qrserver.com/tec-it.com being up
 * and reachable at that exact moment, every single time anyone looked
 * at an ID card. Reported as breaking repeatedly, across all accounts.
 * The actual content of a member's QR/barcode never changes once
 * generated (etel_id -> verify URL is permanent), so there's no reason
 * to depend on the external service more than once per member per
 * size/style combination, ever. Now: fetch once, save the PNG locally
 * under wp-content/uploads/etelid-qr/, serve that local file on every
 * later request. If the external service is unreachable exactly when
 * a *new* code needs generating for the first time, this falls back to
 * the old live-hotlink behavior for that one request rather than
 * showing nothing - so this is strictly safer than before, never worse.
 */
if ( ! defined( 'ABSPATH' ) ) exit;

class EtelID_QR {

    public static function verify_url( $etel_id ) {
        return home_url( '/verify/' . urlencode( $etel_id ) );
    }

    /* Local cache directory/URL, created on first use. Kept out of the
     * normal year/month upload subfolders since these aren't user
     * uploads - a flat, predictable folder is easier to find/clear if
     * ever needed (e.g. after intentionally changing colors/size and
     * wanting to force regeneration). */
    private static function cache_dir() {
        $u = wp_upload_dir();
        $dir = trailingslashit( $u['basedir'] ) . 'etelid-qr';
        if ( ! file_exists( $dir ) ) wp_mkdir_p( $dir );
        return $dir;
    }
    private static function cache_url() {
        $u = wp_upload_dir();
        return trailingslashit( $u['baseurl'] ) . 'etelid-qr';
    }

    /* Fetches $remote_src once, saves it to $cache_file, and returns
     * true on success. Kept generic so both img() and barcode_img()
     * share the exact same fetch/cache/fallback logic instead of
     * duplicating it. */
    private static function fetch_and_cache( $remote_src, $cache_file ) {
        $resp = wp_remote_get( $remote_src, array( 'timeout' => 10 ) );
        if ( is_wp_error( $resp ) || wp_remote_retrieve_response_code( $resp ) !== 200 ) return false;
        $body = wp_remote_retrieve_body( $resp );
        if ( ! $body ) return false;
        return (bool) file_put_contents( $cache_file, $body );
    }

    /* $size is the resolution actually requested from/generated by the
     * QR service (and the cache-file key, alongside color/bgcolor) -
     * $display_size lets a caller show it smaller than that without
     * generating (and caching) a second, separate variant just for a
     * different display width. Defaults to $size when omitted, so the
     * one existing caller (card-back.php, size 120, no color args) is
     * completely unaffected by this signature change. */
    /* Resolves to a cached-if-possible URL string (not a full <img> tag) -
     * shared by img() below and any other caller (like portal_data()'s
     * JSON API response in class-etelid-auth-ajax.php) that needs just
     * the src, not a rendered tag. Both funnel through here so there's
     * exactly one place that knows about caching/fallback, instead of
     * each caller reimplementing it (which is exactly how the portal.php
     * and card_qr_src instances ended up bypassing the cache entirely -
     * each one built its own raw qrserver.com URL independently instead
     * of going through a shared method at all). */
    public static function src( $etel_id, $size = 160, $color = '1a0a00', $bgcolor = 'f5f0e0', $margin = 4 ) {
        $size    = (int) $size;
        $color   = ltrim( (string) $color, '#' );
        $bgcolor = ltrim( (string) $bgcolor, '#' );
        $margin  = (int) $margin;

        $remote_src = 'https://api.qrserver.com/v1/create-qr-code/?size=' . $size . 'x' . $size
             . '&data=' . urlencode( self::verify_url( $etel_id ) )
             . '&color=' . $color . '&bgcolor=' . $bgcolor . '&margin=' . $margin . '&ecc=H';

        $filename   = 'qr-' . sanitize_file_name( $etel_id ) . '-' . $size . '-' . $color . '-' . $bgcolor . '-' . $margin . '.png';
        $cache_file = self::cache_dir() . '/' . $filename;
        $src        = self::cache_url() . '/' . $filename;

        if ( ! file_exists( $cache_file ) ) {
            if ( ! self::fetch_and_cache( $remote_src, $cache_file ) ) {
                // Couldn't cache it right now - fall back to the live
                // URL for this one request rather than returning
                // something that 404s.
                return $remote_src;
            }
        }
        return $src;
    }

    public static function img( $etel_id, $size = 160, $color = '1a0a00', $bgcolor = 'f5f0e0', $display_size = null, $margin = 4 ) {
        $display_size = $display_size !== null ? (int) $display_size : (int) $size;
        $src = self::src( $etel_id, $size, $color, $bgcolor, $margin );
        return '<img src="' . esc_url( $src ) . '" alt="' . esc_attr( $etel_id ) . '" width="' . $display_size . '" height="' . $display_size . '">';
    }

    public static function barcode_img( $value, $w = 220, $h = 40 ) {
        $clean = preg_replace( '/[^A-Za-z0-9]/', '', $value );
        $remote_src = 'https://barcode.tec-it.com/barcode.ashx?data=' . urlencode( $clean )
               . '&code=Code128&dpi=96&unit=Fit&imagetype=Png&rotation=0';

        $filename   = 'bc-' . sanitize_file_name( $clean ) . '.png';
        $cache_file = self::cache_dir() . '/' . $filename;
        $src        = self::cache_url() . '/' . $filename;

        if ( ! file_exists( $cache_file ) ) {
            if ( ! self::fetch_and_cache( $remote_src, $cache_file ) ) {
                $src = $remote_src;
            }
        }

        return '<img src="' . esc_url( $src ) . '" alt="Barcode" style="width:' . (int)$w . 'px;height:' . (int)$h . 'px;display:block;">';
    }
}
