function sgSwitchLang(lang) {
    if (ETEL_I18N.current() !== lang) ETEL_I18N.apply(lang);
    Array.prototype.forEach.call(document.querySelectorAll('.sg-lang-b'), function (b) {
        var on = b.getAttribute('data-lang') === lang;
        b.classList.toggle('on', on); b.setAttribute('aria-pressed', on ? 'true' : 'false');
    });
    // redraw the parts that are built from script
    try {
        if (typeof updateOnlineStatusUI === 'function') updateOnlineStatusUI();
        var vis = function (id) { var e = document.getElementById(id); return e && e.style.display !== 'none'; };
        if (vis('page-services') && typeof renderServices === 'function' && typeof servicesCache !== 'undefined') renderServices(servicesCache);
        if (vis('page-analytics') && typeof loadSalesReport === 'function') loadSalesReport();
        if (vis('page-reviews') && typeof loadSgReviews === 'function') loadSgReviews();
        if (vis('page-settings') && typeof loadUserProfile === 'function') loadUserProfile();
        if (vis('page-staff') && typeof loadRoles === 'function') { loadRoles(); loadStaff(); }
        if (vis('page-payments') && typeof loadSGFinancialReport === 'function') loadSGFinancialReport();
        if (window._sgOrders) { renderRecentOrders(window._sgOrders.slice(0, 5)); renderAllOrders(window._sgOrders); }
        if (typeof loadDashboardData === 'function' && document.getElementById('page-dashboard') && document.getElementById('page-dashboard').style.display !== 'none') loadDashboardData();
    } catch (e) {}
}
