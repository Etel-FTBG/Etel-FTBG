// Run: node tests/hubConfig.test.js   (needs `npm ci` for typescript). Checks the owner's show / hide choices in src/hub/apps.ts with the real file.
const ts = require('typescript'); const fs = require('fs'); const path = require('path'); const Module = require('module');
const src = fs.readFileSync(path.join(__dirname, '../src/hub/apps.ts'), 'utf8');
const js = ts.transpileModule(src, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 } }).outputText;
const m = new Module('apps.js'); m.paths = Module._nodeModulePaths(__dirname);
const origRequire = m.require.bind(m);
m.require = (id) => { if (id === 'expo-constants') return { default: { expoConfig: { extra: {} } } }; if (/\.png$/.test(id)) return 1; return origRequire(id); };
m._compile(js, path.join(__dirname, '../src/hub/apps.js')); const A = m.exports;
let pass = 0; const fails = []; const t = (n, c, x) => { if (c) pass++; else fails.push(n + (x ? ' -> ' + x : '')); };
const app = (k) => A.HUB_APPS.find((a) => a.key === k);
const shown = (role) => A.HUB_APPS.filter((a) => a.status === 'live' && A.hubVisible(a, role)).map((a) => a.key).sort().join(',');

A.applyHubConfig(null);
t('default: live apps on, soon apps off', app('ride').mode === 'on' && app('pay').mode === 'off' && app('admin').mode === 'off');
t('default: customer sees the 9 live apps, not admin or coming soon', shown('customer') === 'agent,courier,customer,driver,equb,id,investor,ride,service', shown('customer'));
t('default: new Staff app exists and is hidden', !!app('admin') && !shown('admin').includes('admin'));
A.applyHubConfig({ admin: { mode: 'admins' } });
t('admins mode: admin sees ETEL Admin', shown('admin').split(',').includes('admin'));
t('admins mode: a customer does not', !shown('customer').split(',').includes('admin'));
t('admins mode: the app is live (it has a built-in address)', app('admin').status === 'live' && /admin\.html/.test(app('admin').url));
A.applyHubConfig({ admin: { mode: 'on' } });
t('on: visible to the role check stage for everyone (the role gate itself is canOpen, in session.ts)', shown('customer').split(',').includes('admin'));
A.applyHubConfig({ agent: { mode: 'off' } });
t('off: Agent hidden for admin and customer', !shown('admin').split(',').includes('agent') && !shown('customer').split(',').includes('agent'));
t('off: the app is parked as soon', app('agent').status === 'soon');
A.applyHubConfig({ pay: { mode: 'on' } });
t('coming-soon app without an address stays closed even if set on', app('pay').status === 'soon' && !shown('admin').split(',').includes('pay'));
A.applyHubConfig({ pay: { mode: 'on', url: 'https://ethelmarket.com/Etel.Pay/wallet/' } });
t('coming-soon app with an address on this site goes live', app('pay').status === 'live' && shown('customer').split(',').includes('pay'));
t('its address gets ?source=app', app('pay').url === 'https://ethelmarket.com/Etel.Pay/wallet/?source=app', app('pay').url);
t('its address is allowed inside the app', A.ALLOWED_ORIGINS.some((o) => 'https://ethelmarket.com/Etel.Pay/wallet/?source=app'.startsWith(o)), JSON.stringify(A.ALLOWED_ORIGINS));
A.applyHubConfig({ pay: { mode: 'on', url: 'https://evil.example.com/x/' } });
t('an address on another site is ignored (second lock)', app('pay').status === 'soon' && app('pay').url === '');
A.applyHubConfig({ pay: { mode: 'on', url: 'http://ethelmarket.com/x/' } });
t('a plain http address is ignored', app('pay').status === 'soon');
A.applyHubConfig({ pay: { mode: 'on', url: 'https://ethelmarket.com.evil.com/x/' } });
t('look-alike host is ignored', app('pay').status === 'soon');
A.applyHubConfig({ pay: { mode: 'on', url: 'https://user@ethelmarket.com/x/' } });
t('address with a user name is ignored', app('pay').status === 'soon');
A.applyHubConfig({ agent: { mode: 'on', url: 'https://ethelmarket.com/delivery/agent2/' } });
t('an app with a built-in address can be moved to another address on this site', app('agent').url === 'https://ethelmarket.com/delivery/agent2/?source=app' && app('agent').status === 'live', app('agent').url);
A.applyHubConfig({ agent: { mode: 'on', url: '' } });
t('empty address = built-in address again', /delivery\/agent\/\?source=app/.test(app('agent').url), app('agent').url);
A.applyHubConfig({ ride: { mode: 'sideways' } });
t('an unknown mode is ignored: Ride keeps its default', app('ride').mode === 'on' && app('ride').status === 'live');
A.applyHubConfig({ nope: { mode: 'on' } });
t('an unknown app key is ignored', A.HUB_APPS.length === 13);
A.applyHubConfig({ admin: { mode: 'on' }, pay: { mode: 'on', url: 'https://ethelmarket.com/p/' } });
A.applyHubConfig(null);
t('clearing the choices puts every default back', app('admin').mode === 'off' && app('pay').status === 'soon' && app('pay').url === '' && A.ALLOWED_ORIGINS.length === 2, A.ALLOWED_ORIGINS.length);
A.applyHubConfig(null);
t('features default to on', A.featureOn('light', 'customer') && A.featureOn('light_alert', 'driver'));
A.applyHubConfig({ light: { mode: 'off' }, light_alert: { mode: 'admins' } });
t('light off: nobody gets it', !A.featureOn('light', 'admin') && !A.featureOn('light', 'customer'));
t('sound admins only: admin yes, driver no', A.featureOn('light_alert', 'admin') && !A.featureOn('light_alert', 'driver'));
A.applyHubConfig({ light: { mode: 'sideways' } });
t('an unknown feature mode is ignored (stays on)', A.featureOn('light', 'customer'));
A.applyHubConfig({ light: { mode: 'off' } });
A.applyHubConfig(null);
t('clearing the choices puts the features back on', A.featureOn('light', 'customer'));
console.log('PASSED: ' + pass + ' FAILED: ' + fails.length); fails.forEach((f) => console.log(' - ' + f)); process.exit(fails.length ? 1 : 0);
