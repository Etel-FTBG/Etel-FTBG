#!/usr/bin/env python3
"""Rebuild EtelId/public/css/etelid-icons.css from the real Tabler Icons (MIT).

    npm pack @tabler/icons@3 && mkdir t && tar -xzf tabler-icons-*.tgz -C t
    python3 tools/etelid-icons/build_icons.py t/package/icons/outline

Scans the plugin for every `ti-<name>` class (plus the names in EXTRA, which are
built dynamically in PHP) and writes one CSS mask rule per icon. Run it again
whenever a template starts using a new icon name; it reports names it cannot find.
"""
import glob, os, re, sys
EXTRA = {'building', 'nfc', 'device-mobile', 'shield-lock'}   # names assembled in PHP (auth-page.php)
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'EtelId')
base = sys.argv[1].rstrip('/') + '/'
names = set(EXTRA)
for f in glob.glob(root + '/**/*', recursive=True):
    if '/tests/' in f or not f.endswith(('.php', '.js', '.css')) or f.endswith('etelid-icons.css'): continue
    names |= set(re.findall(r'\bti-([a-z0-9]+(?:-[a-z0-9]+)*)', open(f, encoding='utf-8', errors='ignore').read()))
names -= {'spin'}
out = ["/* EtelID self-hosted icon set: Tabler Icons (MIT, https://tabler.io/icons) drawn as CSS masks.",
       " * Same .ti .ti-name classes as the old CDN webfont, so no markup changes and no third-party request.",
       " * Generated by tools/etelid-icons/build_icons.py - do not edit by hand. */",
       ".ti{display:inline-block;width:1.15em;height:1.15em;vertical-align:-.2em;background-color:currentColor;-webkit-mask:var(--i) center/contain no-repeat;mask:var(--i) center/contain no-repeat;flex-shrink:0;font-style:normal}",
       "@keyframes ti-spin{to{transform:rotate(360deg)}}", ".ti-spin,.ti-loader,.ti-loader-2{animation:ti-spin 1s linear infinite}"]
missing = []
for n in sorted(names):
    p = base + n + '.svg'
    if not os.path.exists(p): missing.append(n); continue
    s = re.sub(r'<!--.*?-->', '', open(p).read(), flags=re.S).replace('currentColor', '#000')
    s = re.sub(r"\s+", ' ', s).strip()
    s = re.sub(r" class=\"[^\"]*\"", '', s)
    s = s.replace('%', '%25').replace('<', '%3C').replace('>', '%3E').replace('#', '%23').replace('"', "'")
    out.append('.ti-%s{--i:url("data:image/svg+xml,%s")}' % (n, s))
open(root + '/public/css/etelid-icons.css', 'w').write("\n".join(out) + "\n")
print(len(names) - len(missing), 'icons written; missing:', missing or 'none')
